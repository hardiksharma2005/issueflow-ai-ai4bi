import {
  ArrowDown,
  ArrowUp,
  ChevronsUp,
  Circle,
  CircleCheck,
  CircleDashed,
  CircleDot,
  CircleSlash,
  CircleX,
  Equal,
  Eye,
  FlaskConical,
} from "lucide-react";
import { cn } from "@/lib/utils";
import {
  CATEGORY_LABELS,
  IMPORT_STATUS_LABELS,
  PRIORITY_COLOR_VAR,
  PRIORITY_LABELS,
  PROJECT_STATUS_LABELS,
  ROLE_LABELS,
  STATUS_COLOR_VAR,
  STATUS_LABELS,
  type ImportStatus,
  type IssueCategory,
  type IssuePriority,
  type IssueStatus,
  type ProjectStatus,
  type Role,
} from "@/lib/domain";

const pill = "inline-flex items-center gap-1.5 whitespace-nowrap rounded-md border px-1.5 py-0.5 text-xs font-medium";

const STATUS_ICON: Record<IssueStatus, typeof Circle> = {
  open: Circle,
  in_progress: CircleDot,
  blocked: CircleSlash,
  in_review: Eye,
  resolved: CircleCheck,
  closed: CircleX,
};

export function StatusIcon({ status, className }: { status: IssueStatus; className?: string }) {
  const Icon = STATUS_ICON[status];
  return <Icon aria-hidden className={cn("size-3.5 shrink-0", className)} style={{ color: STATUS_COLOR_VAR[status] }} />;
}

export function StatusBadge({ status, className }: { status: IssueStatus; className?: string }) {
  return (
    <span className={cn(pill, "bg-background", className)}>
      <StatusIcon status={status} />
      {STATUS_LABELS[status]}
    </span>
  );
}

const PRIORITY_ICON: Record<IssuePriority, typeof Circle> = {
  critical: ChevronsUp,
  high: ArrowUp,
  medium: Equal,
  low: ArrowDown,
};

export function PriorityIcon({ priority, className }: { priority: IssuePriority; className?: string }) {
  const Icon = PRIORITY_ICON[priority];
  return <Icon aria-hidden className={cn("size-3.5 shrink-0", className)} style={{ color: PRIORITY_COLOR_VAR[priority] }} />;
}

export function PriorityBadge({ priority, className }: { priority: IssuePriority; className?: string }) {
  return (
    <span className={cn(pill, "bg-background", className)}>
      <PriorityIcon priority={priority} />
      {PRIORITY_LABELS[priority]}
    </span>
  );
}

export function CategoryBadge({ category }: { category: IssueCategory }) {
  return <span className={cn(pill, "border-transparent bg-muted text-muted-foreground")}>{CATEGORY_LABELS[category]}</span>;
}

const IMPORT_TONE: Record<ImportStatus, string> = {
  uploaded: "text-muted-foreground",
  parsing: "text-[var(--status-progress)]",
  parsed: "text-[var(--status-progress)]",
  processing: "text-[var(--status-progress)]",
  review: "text-[var(--status-review)]",
  completed: "text-[var(--status-resolved)]",
  failed: "text-[var(--status-blocked)]",
  duplicate: "text-[var(--priority-high)]",
};

export function ImportStatusBadge({ status }: { status: ImportStatus }) {
  return (
    <span className={cn(pill, "bg-background")}>
      <CircleDashed aria-hidden className={cn("size-3.5", IMPORT_TONE[status])} />
      {IMPORT_STATUS_LABELS[status]}
    </span>
  );
}

export function ProjectStatusBadge({ status }: { status: ProjectStatus }) {
  const tone =
    status === "active" ? "var(--status-resolved)" : status === "on_hold" ? "var(--priority-high)" : "var(--status-closed)";
  return (
    <span className={cn(pill, "bg-background")}>
      <span aria-hidden className="size-1.5 rounded-full" style={{ background: tone }} />
      {PROJECT_STATUS_LABELS[status]}
    </span>
  );
}

export function RoleBadge({ role }: { role: Role }) {
  return (
    <span
      className={cn(
        pill,
        role === "admin" && "border-primary/30 bg-primary/10 text-primary",
        role === "manager" && "bg-accent text-accent-foreground",
        role === "member" && "text-muted-foreground",
      )}
    >
      {ROLE_LABELS[role]}
    </span>
  );
}

/** Shown wherever AI output came from the mock provider. Never hidden. */
export function SimulatedBadge({ className }: { className?: string }) {
  return (
    <span
      className={cn(pill, "border-amber-500/30 bg-amber-500/10 text-amber-700 dark:text-amber-400", className)}
      title="Generated by the MockAIProvider in demo mode — no AI model was called."
    >
      <FlaskConical aria-hidden className="size-3.5" />
      Simulated AI
    </span>
  );
}

export function ConfidenceMeter({ value }: { value: number }) {
  const pct = Math.round(value * 100);
  const tone = pct >= 75 ? "var(--status-resolved)" : pct >= 50 ? "var(--priority-medium)" : "var(--priority-high)";
  return (
    <span className="inline-flex items-center gap-1.5 text-xs text-muted-foreground" title="AI confidence that this is a distinct, actionable issue">
      <span className="h-1.5 w-12 overflow-hidden rounded-full bg-muted" aria-hidden>
        <span className="block h-full rounded-full" style={{ width: `${pct}%`, background: tone }} />
      </span>
      <span className="tabular-nums">{pct}%</span>
    </span>
  );
}
